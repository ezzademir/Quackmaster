#!/usr/bin/env python3
"""Generate supabase/seeds/costing_seed_20261023.sql from the cleaned procurement CSVs.

Usage: python3 scripts/generate_costing_seed.py <cleaned_dir> <clean_state.pkl> [out.sql]

clean_state.pkl is clean.py's state (wastage and servings per BOM sheet, which the CSVs do not carry).

The output is NOT a migration and is never applied automatically. It is idempotent
(ON CONFLICT / NOT EXISTS) and wraps everything in one transaction.
Rules: unknown costs stay NULL with cost_complete=false; nothing is estimated.
"""
import csv, sys, os, collections, pickle

SRC_LIST = 'MASTER_LIST_2_20261023'
TAG = {'QUACKTEOW': 'quackteow', 'MERDEKA HOUSE PLT': 'merdeka_house'}
ENTITY = {'MERDEKA HOUSE PLT': 'MH_PLT', 'QUACKTEOW PLT': 'QT_PLT', 'QUACKTEOW ENTERPRISE': 'QT_ENT'}


def q(v):
    if v is None or v == '':
        return 'NULL'
    return "'" + str(v).replace("'", "''") + "'"


def num(v):
    v = (v or '').strip()
    if v == '':
        return 'NULL'
    float(v)
    return v


def b(v):
    return 'true' if str(v).strip().lower() == 'true' else 'false'


def basis(v):
    v = (v or '').strip().lower()
    if v.startswith('pending'):
        return 'pending'
    if v.startswith('receipt'):
        return 'receipt'
    if v.startswith('list'):
        return 'list'
    raise ValueError(f'unknown price_basis {v!r}')


def main():
    src = sys.argv[1]
    state = pickle.load(open(sys.argv[2], 'rb'))
    ysheet = {d['sheet']: (d['_w'], d['_sv']) for d in state[2]}
    out = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(__file__), '..', 'supabase', 'seeds', 'costing_seed_20261023.sql')
    S = list(csv.DictReader(open(os.path.join(src, 'suppliers_clean.csv'))))
    B = list(csv.DictReader(open(os.path.join(src, 'bom_lines_clean.csv'))))
    D = list(csv.DictReader(open(os.path.join(src, 'dish_costs.csv'))))
    L = []
    w = L.append
    stats = collections.Counter()
    w('-- GENERATED by scripts/generate_costing_seed.py from cleaned procurement CSVs (23 Oct 2026, rev 2).')
    w('-- NOT a migration. Do not run until 082/083 are applied and an admin has reviewed the data.')
    w('-- Unknown costs are NULL with cost_complete=false; nothing is estimated.')
    w('BEGIN;')
    w("SELECT set_config('app.price_source', 'seed', true);")
    w("SELECT set_config('app.price_note', 'seed: suppliers master list 23 Oct 2026', true);")

    # suppliers (shared)
    sup = collections.OrderedDict()
    for r in S:
        sup.setdefault(r['supplier_clean'].strip(), r)
    w('\n-- suppliers (%d)' % len(sup))
    for name, r in sup.items():
        w(f"INSERT INTO public.suppliers (name, payment_terms, delivery_day, status) SELECT {q(name)}, {q(r['payment_terms_clean'])}, {q(r['delivery_day'])}, 'active' "
          f"WHERE NOT EXISTS (SELECT 1 FROM public.suppliers WHERE lower(trim(name)) = lower({q(name)}));")
    stats['suppliers'] = len(sup)

    # ingredients (shared) + supplier items
    ing = collections.OrderedDict()
    for r in S:
        ing.setdefault((r['item_clean'].strip().lower(), r['base_unit']), r)
    w('\n-- ingredients (%d)' % len(ing))
    for (_, unit), r in ing.items():
        w(f"INSERT INTO public.ingredients (name, base_unit, in_house, status) VALUES ({q(r['item_clean'].strip())}, {q(unit)}, {b(r['in_house'])}, 'active') "
          f"ON CONFLICT (lower(name), base_unit) DO NOTHING;")
    stats['ingredients'] = len(ing)
    w('\n-- supplier_items (%d)' % len(S))
    for r in S:
        pb = basis(r['price_basis'])
        price = 'NULL' if pb == 'pending' else num(r['price_rm'])
        tag = TAG[r['entity'].strip()]
        stats[f'supplier_items:{tag}'] += 1
        if price == 'NULL':
            stats['supplier_items:price_null'] += 1
        note = r['issues'] or None
        if r['price_basis'].strip() != pb:
            note = '; '.join(x for x in [r['price_basis'].strip(), note] if x)
        w('INSERT INTO public.supplier_items (supplier_id, ingredient_id, procurement_tag, shared_ingredient, item_name, pack_qty, pack_unit, base_unit, '
          'pack_qty_base, price_rm, price_basis, payment_terms, delivery_day, status, source_list, source_line_no, notes, approved_at) '
          f"SELECT s.id, i.id, {q(tag)}, {b(r['shared_ingredient'])}, {q(r['item_raw'].strip())}, {num(r['pack_qty'])}, {q(r['pack_unit_raw'])}, {q(r['base_unit'])}, "
          f"{num(r['pack_qty_base'])}, {price}, {q(pb)}, {q(r['payment_terms_clean'])}, {q(r['delivery_day'])}, {q(r['status'])}, {q(SRC_LIST)}, {int(r['line_no'])}, {q(note)}, now() "
          f"FROM public.suppliers s, public.ingredients i WHERE lower(trim(s.name)) = lower({q(r['supplier_clean'].strip())}) "
          f"AND lower(i.name) = lower({q(r['item_clean'].strip())}) AND i.base_unit = {q(r['base_unit'])} "
          f"ORDER BY s.created_at LIMIT 1 ON CONFLICT (source_list, source_line_no) WHERE source_line_no IS NOT NULL DO NOTHING;")

    # menu items / sub-recipes
    w('\n-- menu_items and sub_recipes (%d)' % len(D))
    sheets = {}
    for r in D:
        ent = ENTITY[r['entity'].strip()]
        sheet = r['sheet']
        sheets[(r['entity'].strip(), sheet)] = r['kind']
        stats[f"{r['kind']}:{ent}:{r['status']}"] += 1
        if r['cost_complete'] != 'True':
            stats[f"{r['kind']}:incomplete"] += 1
        notes = r['issues'] or None
        wst, sv = ysheet[sheet]
        wpct = repr(round(float(wst) * 100, 4))
        sv = repr(float(sv))
        if r['kind'] == 'dish':
            w('INSERT INTO public.menu_items (entity_code, name, status, selling_price_ex_sst_rm, packaging_rule, pkg_dine_in_rm, pkg_takeaway_rm, wastage_pct, servings, source_sheet, notes) '
              f"VALUES ({q(ent)}, {q(r['menu_item'])}, {q(r['status'])}, {num(r['selling_price'])}, {q(r['packaging_rule'])}, {num(r['pkg_dine_in_rm'])}, "
              f"{num(r['pkg_takeaway_rm'])}, {wpct}, {sv}, {q(sheet)}, {q(notes)}) ON CONFLICT (entity_code, source_sheet) DO NOTHING;")
        else:
            w('INSERT INTO public.sub_recipes (entity_code, name, status, yield_note, selling_price_ex_sst_rm, wastage_pct, servings, source_sheet, notes) '
              f"VALUES ({q(ent)}, {q(r['menu_item'])}, {q(r['status'])}, {q(r['yield_note'])}, {num(r['selling_price'])}, {wpct}, {sv}, {q(sheet)}, {q(notes)}) "
              'ON CONFLICT (entity_code, source_sheet) DO NOTHING;')
        if r['packaging_rule'] and not r['pkg_takeaway_rm']:
            stats['dish:pkg_takeaway_null'] += 1

    sub_by_sheet = {s.strip().upper(): s for (e, s), k in sheets.items() if k == 'sub-recipe'}
    w('\n-- bom_lines')
    for r in B:
        if (r['qty'] or '').strip() == '':
            stats['bom:skipped_stray_label'] += 1
            continue
        ent_name = r['entity'].strip()
        ent = ENTITY[ent_name]
        kind = sheets.get((ent_name, r['sheet']))
        if kind is None:
            raise SystemExit(f"BOM sheet {r['sheet']!r} has no dish_costs row")
        pb = basis(r['price_basis'])
        cost = num(r['line_cost'])
        complete = cost != 'NULL' and pb != 'pending'
        stats[f'bom:{ent}:{r["status"]}'] += 1
        if not complete:
            stats['bom:incomplete'] += 1
            cost = 'NULL' if pb == 'pending' else cost
        parent_tbl = 'menu_items' if kind == 'dish' else 'sub_recipes'
        parent_col = 'menu_item_id' if kind == 'dish' else 'sub_recipe_id'
        line_no = r['matched_supplier_line'].strip()
        si = (f"(SELECT id FROM public.supplier_items WHERE source_list = {q(SRC_LIST)} AND source_line_no = {int(line_no)})"
              if line_no.isdigit() else 'NULL')
        mi = (r['matched_item'] or '').strip().upper()
        sub = (f"(SELECT id FROM public.sub_recipes WHERE entity_code = {q(ent)} AND source_sheet = {q(sub_by_sheet[mi])})"
               if not line_no.isdigit() and mi in sub_by_sheet else 'NULL')
        w(f'INSERT INTO public.bom_lines (entity_code, {parent_col}, component_name, supplier_item_id, component_sub_recipe_id, qty, unit, base_qty, '
          'price_basis, line_cost_rm, cost_complete, shared_ingredient, status, source_sheet, source_row, issues) '
          f"SELECT {q(ent)}, p.id, {q(r['component'])}, {si}, {sub}, {num(r['qty'])}, {q(r['unit'])}, {num(r['base_qty'])}, {q(pb)}, {cost}, "
          f"{'true' if complete else 'false'}, {b(r['shared_ingredient'])}, {q(r['status'])}, {q(r['sheet'])}, {int(r['sheet_row'])}, {q(r['issues'] or None)} "
          f"FROM public.{parent_tbl} p WHERE p.entity_code = {q(ent)} AND p.source_sheet = {q(r['sheet'])} "
          f"AND NOT EXISTS (SELECT 1 FROM public.bom_lines x WHERE x.entity_code = {q(ent)} AND x.source_sheet = {q(r['sheet'])} AND x.source_row = {int(r['sheet_row'])});")
        stats['bom:lines'] += 1
    w('\nCOMMIT;')
    w('\n-- counts: ' + ', '.join(f'{k}={v}' for k, v in sorted(stats.items())))
    open(out, 'w').write('\n'.join(L) + '\n')
    for k, v in sorted(stats.items()):
        print(f'{k}\t{v}')


if __name__ == '__main__':
    main()
